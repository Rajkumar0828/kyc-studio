// Renders the README's "See the model's output" images and section from an eval
// results.json: each specimen image with the model's boxes (red, labelled with the
// extracted value) and the ground-truth boxes (green, dashed). Offline: reads the
// results file and the specimen PNGs only, uses sharp, no network.
//
//   npx tsx scripts/render-readme-overlays.ts [results.json]           render images, print the README section
//   npx tsx scripts/render-readme-overlays.ts [results.json] --check   README section and images match results.json
//
// Defaults: docs/eval/2026-11-02-full-eval-effort-low.results.json (a copy of
// eval/reports/2026-11-02T04-31-53-701Z/results.json), eval/specimens, docs/eval/images.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(__dirname, "..", "..");
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const RESULTS = path.resolve(args.find((a) => !a.startsWith("--")) ?? path.join(ROOT, "docs", "eval", "2026-11-02-full-eval-effort-low.results.json"));
const SPECIMENS = path.join(ROOT, "eval", "specimens");
const OUT = path.join(ROOT, "docs", "eval", "images");
const README = path.join(ROOT, "README.md");
const START = "<!-- model-output:start (generated by frontend/scripts/render-readme-overlays.ts; do not edit by hand) -->";
const END = "<!-- model-output:end -->";
const MAX_WIDTH = 1200;

type Box = [number, number, number, number]; // [x_min, y_min, x_max, y_max], 0-1000 grid
interface Field { field: string; truthFound: boolean; modelFound: boolean; truth: string | null; model: string | null; modelBox: Box | null; truthBox: Box | null; valuePass: boolean; iou: number | null; boxPass: boolean | null; diagnostics: { dyPct: number } | null }
interface Doc { doc: string; fields: Field[] }
interface Case { caseId: string; decision: string; codes: string[]; docs: Doc[] }
interface Results { run: { startedAt: string; model: string; reasoningEffort: Record<string, string> }; cases: Case[] }

// The four documents asked for, plus the run's lowest box pass rate (a miss).
const CHOSEN = ["p1-clean/id.png", "p1-clean/bill.png", "p2-name-mismatch/bill.png", "p1-expired/id.png"];

const WHY: Record<string, string> = {
  document_expired: "the ID card has expired",
  full_name_mismatch: "the bill is in another person's name",
  address_mismatch: "the bill is for a different address",
  quality_failed: "the photos failed the quality check",
};

const boxStats = (d: Doc) => {
  const scored = d.fields.filter((f) => f.truthFound);
  return { pass: scored.filter((f) => f.boxPass).length, total: scored.length };
};

function pick(results: Results) {
  const all = results.cases.flatMap((c) => c.docs.map((d) => ({ c, d })));
  const find = (doc: string) => {
    const hit = all.find((x) => x.d.doc === doc);
    if (!hit) throw new Error(`${doc} is not in ${RESULTS}`);
    return hit;
  };
  const extracted = all.filter((x) => boxStats(x.d).total > 0);
  const miss = extracted.reduce((a, x) => (boxStats(x.d).pass / boxStats(x.d).total < boxStats(a.d).pass / boxStats(a.d).total ? x : a));
  const chosen = CHOSEN.map((doc) => ({ ...find(doc), miss: false }));
  if (!CHOSEN.includes(miss.d.doc)) chosen.push({ ...miss, miss: true });
  return chosen;
}

const imageName = (doc: string) => `${doc.replace(/\.png$/, "").replace(/\//g, "-")}.png`;
const cell = (s: string) => s.replace(/\|/g, "\\|");
const shown = (found: boolean, v: string | null) => (found && v !== null ? v : "(absent)");

export function buildSection(results: Results): string {
  const effort = results.run.reasoningEffort.extraction;
  const lines: string[] = [
    START,
    "## See the model's output",
    "",
    `Real output from the full eval at effort ${effort} (\`${results.run.model}\`, run ${results.run.startedAt}). **Red** boxes are the model's, labelled with the value it extracted; **green dashed** boxes are the ground truth. Boxes are approximate: they are on a 0–1000 grid, and a box passes when its centre lies inside the truth box and IoU ≥ 0.4. All documents are synthetic and marked SPECIMEN. Full details: [the report](docs/eval/2026-11-02-full-eval-effort-low.md) and [its results.json](docs/eval/2026-11-02-full-eval-effort-low.results.json).`,
    "",
  ];
  for (const { c, d, miss } of pick(results)) {
    const { pass, total } = boxStats(d);
    const why = c.codes.length ? c.codes.map((k) => WHY[k] ?? k).join("; ") : "no flags were raised";
    const flags = c.codes.length ? ` (${c.codes.map((k) => `\`${k}\``).join(", ")})` : "";
    const values = `${d.fields.filter((f) => f.valuePass).length} of ${d.fields.length} values match`;
    const dys = d.fields.filter((f) => f.truthFound && !f.boxPass && f.diagnostics).map((f) => f.diagnostics!.dyPct);
    const offset = dys.length
      ? `; the failed boxes sit ${Math.min(...dys)}% to ${Math.max(...dys)}% of the page height ${Math.min(...dys) >= 0 ? "below" : "off"} the truth boxes`
      : "";
    const caption = miss
      ? `**\`${d.doc}\`: a miss.** The lowest box pass rate in the run: ${values}, but ${pass} of ${total} boxes pass${offset}. The case still decided \`${c.decision}\`${flags} because ${why}.`
      : `**\`${d.doc}\`**: decided \`${c.decision}\`${flags} because ${why}. ${values}; ${pass} of ${total} boxes pass.`;
    lines.push(caption, "", `![${d.doc}: model boxes in red, ground truth in green dashed](docs/eval/images/${imageName(d.doc)})`, "",
      "| Field | Ground truth | Model value | Value match | Box IoU |", "|---|---|---|---|---|");
    for (const f of d.fields)
      lines.push(`| ${f.field} | ${cell(shown(f.truthFound, f.truth))} | ${cell(shown(f.modelFound, f.model))} | ${f.valuePass ? "✓" : "✗"} | ${f.iou === null ? "–" : f.iou.toFixed(2)} |`);
    lines.push("");
  }
  lines.push(END);
  return lines.join("\n");
}

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const FONT = "DejaVu Sans, Segoe UI, Arial, sans-serif";

async function render(d: Doc): Promise<Buffer> {
  const src = sharp(path.join(SPECIMENS, d.doc));
  const meta = await src.metadata();
  const W = Math.min(MAX_WIDTH, meta.width!), H = Math.round((meta.height! * W) / meta.width!);
  const px = (b: Box) => ({ x: (b[0] / 1000) * W, y: (b[1] / 1000) * H, w: ((b[2] - b[0]) / 1000) * W, h: ((b[3] - b[1]) / 1000) * H });
  const fs = Math.max(13, Math.round(W / 80)), pad = 4, labelH = fs + pad * 2;
  const parts: string[] = [];
  for (const f of d.fields) if (f.truthFound && f.truthBox) {
    const r = px(f.truthBox);
    parts.push(`<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="none" stroke="#16a34a" stroke-width="3" stroke-dasharray="8 5"/>`);
  }
  for (const f of d.fields) if (f.modelFound && f.modelBox) {
    const r = px(f.modelBox);
    const text = f.model && f.model.length > 36 ? `${f.model.slice(0, 35)}…` : f.model ?? "";
    const tw = text.length * fs * 0.6 + pad * 2;
    const ly = r.y - labelH - 2 >= 0 ? r.y - labelH - 2 : r.y + r.h + 2;
    const lx = Math.min(r.x, W - tw);
    parts.push(`<rect x="${r.x}" y="${r.y}" width="${r.w}" height="${r.h}" fill="none" stroke="#dc2626" stroke-width="3"/>`,
      `<rect x="${lx}" y="${ly}" width="${tw}" height="${labelH}" rx="3" fill="#dc2626"/>`,
      `<text x="${lx + pad}" y="${ly + labelH - pad - 2}" font-family="${FONT}" font-size="${fs}" font-weight="600" fill="#fff">${esc(text)}</text>`);
  }
  const LEGEND = Math.round(fs * 3.4);
  const ly = H + LEGEND / 2;
  const legend = [
    `<rect x="0" y="${H}" width="${W}" height="${LEGEND}" fill="#ffffff"/>`,
    `<line x1="0" y1="${H}" x2="${W}" y2="${H}" stroke="#cbd5e1" stroke-width="1"/>`,
    `<rect x="16" y="${ly - fs / 2}" width="${fs * 1.6}" height="${fs}" fill="none" stroke="#dc2626" stroke-width="3"/>`,
    `<text x="${16 + fs * 2.1}" y="${ly + fs * 0.35}" font-family="${FONT}" font-size="${fs}" fill="#0f172a">Model box and extracted value</text>`,
    `<rect x="${16 + fs * 17}" y="${ly - fs / 2}" width="${fs * 1.6}" height="${fs}" fill="none" stroke="#16a34a" stroke-width="3" stroke-dasharray="6 4"/>`,
    `<text x="${16 + fs * 19.1}" y="${ly + fs * 0.35}" font-family="${FONT}" font-size="${fs}" fill="#0f172a">Ground truth</text>`,
    `<text x="${W - 16}" y="${ly + fs * 0.35}" text-anchor="end" font-family="${FONT}" font-size="${Math.round(fs * 0.85)}" fill="#475569">Synthetic specimen · boxes approximate</text>`,
  ];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H + LEGEND}">${parts.join("")}${legend.join("")}</svg>`;
  return src.resize(W).extend({ bottom: LEGEND, background: "#ffffff" })
    .composite([{ input: Buffer.from(svg), top: 0, left: 0 }])
    .png({ palette: true, quality: 90, compressionLevel: 9, effort: 10 })
    .toBuffer();
}

async function main() {
  const results = JSON.parse(fs.readFileSync(RESULTS, "utf8")) as Results;
  const section = buildSection(results);
  const docs = pick(results);
  if (CHECK) {
    const readme = fs.readFileSync(README, "utf8").replace(/\r\n/g, "\n");
    const a = readme.indexOf(START), b = readme.indexOf(END);
    const problems: string[] = [];
    if (a < 0 || b < 0) problems.push("README has no generated model-output section");
    else if (readme.slice(a, b + END.length) !== section) problems.push("README model-output section differs from what results.json produces (regenerate it)");
    for (const { d } of docs) if (!fs.existsSync(path.join(OUT, imageName(d.doc)))) problems.push(`missing image ${imageName(d.doc)}`);
    if (problems.length) {
      console.log(problems.map((p) => `FAIL  ${p}`).join("\n"));
      process.exit(1);
    }
    const rows = docs.reduce((n, x) => n + x.d.fields.length, 0);
    console.log(`PASS  README model-output section: ${docs.length} documents, ${rows} table rows, all from ${path.relative(ROOT, RESULTS)}`);
    return;
  }
  fs.mkdirSync(OUT, { recursive: true });
  for (const { d } of docs) {
    const file = path.join(OUT, imageName(d.doc));
    fs.writeFileSync(file, await render(d));
    const m = await sharp(file).metadata();
    console.error(`wrote ${path.relative(ROOT, file)} ${m.width}x${m.height} ${fs.statSync(file).size} bytes`);
  }
  console.log(section);
}
void main();
